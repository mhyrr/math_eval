#!/usr/bin/env python3
"""
Phase 4 aggregate analysis: per-tag rates, the conditional Route N column, and
the B2 sensitivity band.

    python3 scripts/analyse4.py > survey4/RESULTS.md

Reads survey4/*.yaml only. Does NOT touch the reveal snapshot -- this runs at
stage 2, before outcomes are known.

THREE THINGS score.py DOES NOT PRINT, all of them needed to report honestly:

1. PER-TAG RATES. P2 is the prediction this test can actually settle and it is
   a cross-field contrast, which the aggregate hides.

2. CONDITIONAL ROUTE N. route_n requires g0_checked_rigorously, --optimistic
   does not grant it (it is not in GATES), and G0 cannot be discharged at this
   scale. So Route N scores zero on all 56 whatever the territory looks like,
   and P4 would fail by construction rather than by evidence. The conditional
   column counts rows that would clear Route N if G0 were discharged --
   prior_attention LOW and certificate_cost >= 3. Pre-registered before scoring
   (memo/PREREGISTRATION.md, Appendix B, 2026-07-25).

3. B2 SENSITIVITY. RUBRIC.md's B2=3 anchor ("mathlib covers the ambient
   theory") admits more than one reading, and on this sample the readings are
   worth 27 points. Reporting one number without the band would be reporting a
   judgement call as a measurement.
"""

import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import yaml
from score import score, ROUTES

ROOT = Path(__file__).resolve().parent.parent
SURVEY = ROOT / "survey4"


def load():
    out = []
    for f in sorted(SURVEY.glob("*.yaml")):
        d = yaml.safe_load(f.read_text())
        d.setdefault("id", f.stem)
        out.append(d)
    return out


# The alternate reading actually weighed while scoring: drop the
# "not asymptotic" refinement and score B2=3 wherever the OBJECTS are
# elementary-arithmetic or finite-combinatorial with mature mathlib apparatus,
# whether or not the question is asymptotic. Six rows move (9, 295, 304, 312,
# 342, 539) -- all elementary objects, all asymptotic questions.
AMBIENT_BROAD = {"7", "9", "11", "85", "282", "288", "291", "295", "304",
                 "312", "317", "342", "539", "617", "619", "681", "830", "849"}


def rate(probs, b2_cap=None, b2_floor_ids=None):
    """CANDIDATE count under a B2 variant. b2_cap caps every row's B2."""
    n = 0
    for p in probs:
        q = dict(p)
        num = q["id"].split("-")[0][1:]
        if b2_cap is not None:
            q["formal_library_coverage"] = min(q["formal_library_coverage"], b2_cap)
        if b2_floor_ids and num in b2_floor_ids:
            q["formal_library_coverage"] = max(q["formal_library_coverage"], 3)
        if score(q, optimistic=True)["verdict"] == "CANDIDATE":
            n += 1
    return n


def main():
    P = load()
    N = len(P)
    res = {p["id"]: score(p, optimistic=True) for p in P}
    cand = [p for p in P if res[p["id"]]["verdict"] == "CANDIDATE"]

    print("# Phase 4 survey results — 56 problems, scored blind\n")
    print("Generated by `scripts/analyse4.py`. **Stage 2 output: written and "
          "committed before the reveal snapshot was read.**\n")

    print("## Headline\n")
    print("| reading | CANDIDATE | rate |")
    print("|---|---|---|")
    print(f"| strict (G1 undischarged → all UNDETERMINED) | 0 | **0%** |")
    print(f"| optimistic (G1 granted; G0 and G2 assessed) | {len(cand)} | "
          f"**{len(cand)/N:.0%}** |")
    print()
    print("The strict column measures **G1 availability, not the rubric**. G1 "
          "is null on all 56 because whether an open problem needs new theory "
          "is not answerable from a redacted Lean file and a status database. "
          "Every row therefore returns UNDETERMINED and the number carries no "
          "information about the territory.\n")
    print("The optimistic column is **stronger here than it was in Phase 3**. "
          "G0 and G2 are set explicitly on every row, so `--optimistic` grants "
          "exactly one gate — G1 — rather than papering over three.\n")

    print("## Per-tag rates (P2)\n")
    bytag = defaultdict(list)
    for p in P:
        bytag[p["area"]].append(p)
    print("| tag | n | CANDIDATE | rate | routes used |")
    print("|---|---|---|---|---|")
    rates = {}
    for t in sorted(bytag):
        ps = bytag[t]
        c = [p for p in ps if res[p["id"]]["verdict"] == "CANDIDATE"]
        rc = Counter()
        for p in c:
            for r in res[p["id"]]["cleared"]:
                rc[r.split()[0]] += 1
        rates[t] = len(c) / len(ps)
        used = ", ".join(f"{k}×{v}" for k, v in sorted(rc.items())) or "—"
        print(f"| {t} | {len(ps)} | {len(c)} | {len(c)/len(ps):.0%} | {used} |")
    hi, lo = max(rates.values()), min(rates.values())
    nonzero = min(v for v in rates.values() if v > 0)
    print()
    print(f"**Spread: {hi:.0%} to {lo:.0%}.** Two tags score zero, so the "
          f"highest-to-lowest ratio is undefined; against the lowest *nonzero* "
          f"tag it is {hi/nonzero:.1f}×.\n")

    print("## Route usage\n")
    rc = Counter()
    for p in P:
        for r in res[p["id"]]["cleared"]:
            rc[r.split()[0]] += 1
    print("| route | clearances | problems |")
    print("|---|---|---|")
    for tag, name, _ in ROUTES:
        ids = [p["id"] for p in P if any(c.startswith(tag)
                                         for c in res[p["id"]]["cleared"])]
        print(f"| {tag} ({name}) | {rc.get(tag, 0)} | "
              f"{', '.join(i.split('-')[0] for i in ids) or '—'} |")
    print()

    condn = [p for p in P if p.get("prior_attention") == "LOW"
             and p["certificate_cost"] >= 3]
    print(f"**Route N conditional column: {len(condn)} of {N} "
          f"({len(condn)/N:.0%})** would clear Route N if G0 were discharged "
          f"by literature work — `prior_attention == LOW` and "
          f"`certificate_cost >= 3`. Primary count is 0 and stays 0; this is "
          f"the pre-registered secondary reading.\n")
    print("```")
    print(" ".join(sorted((p["id"].split("-")[0][1:] for p in condn), key=int)))
    print("```\n")

    print("## B2 sensitivity — the number that moves\n")
    print("Route F carries 12 of the 14 clearances, and within Route F the "
          "verdict turns on `formal_library_coverage` alone. RUBRIC.md's "
          "anchors admit more than one reading of what \"mathlib covers the "
          "ambient theory\" means:\n")
    tech, broad = rate(P, b2_cap=2), rate(P, b2_floor_ids=AMBIENT_BROAD)
    print("| reading of B2=3 | CANDIDATE | rate |")
    print("|---|---|---|")
    print(f"| **technique** — the proof machinery is a named mathlib theorem. "
          f"Unapplicable to an open problem, since nobody knows its proof, so "
          f"B2 ≤ 2 everywhere | {tech} | **{tech/N:.0%}** |")
    print(f"| **ambient + not-asymptotic** — the bar actually used | "
          f"{len(cand)} | **{len(cand)/N:.0%}** |")
    print(f"| **ambient** — mature apparatus for the objects, asymptotic "
          f"question or not | {broad} | **{broad/N:.0%}** |")
    print()
    print(f"**The band is the finding.** Three defensible readings of one "
          f"anchor sentence give {tech/N:.0%}, {len(cand)/N:.0%} and "
          f"{broad/N:.0%} on the same 56 problems, with every other axis call "
          f"identical. Any single headline rate from this instrument is "
          f"reporting an analyst's reading of one line in `RUBRIC.md` as "
          f"though it were a measurement. The middle reading was fixed in "
          f"`scripts/mk_survey4.py` before the reveal; the other two are "
          f"computed here, also before it.\n")
    print("Only six rows separate the middle reading from the third — #9, "
          "#295, #304, #312, #342, #539 — all of them problems with elementary "
          "objects and asymptotic questions. Whether \"mathlib covers the "
          "ambient theory\" is true of *Egyptian-fraction asymptotics* is the "
          "entire disagreement.\n")

    print("## Blocking conditions\n")
    blockers = Counter()
    for p in P:
        for reasons in res[p["id"]].get("blocked", {}).values():
            for r in reasons:
                blockers[r.split()[0]] += 1
    print("| condition | rows blocked |")
    print("|---|---|")
    for k, v in blockers.most_common():
        print(f"| {k} | {v} |")
    print()
    print("`G0` blocks all 56 — that is Route N's rigorous-G0 requirement, not "
          "a fact about the problems. `reservoir_proximity` at 55 is Route R "
          "closing almost everywhere, which is the same shape Phase 3 found "
          "and for a related reason: these are problems worked from inside "
          "their own fields.\n")

    print("## The 14\n")
    print("| # | tag | verdict route | A | B1 | B2 | C | D | E |")
    print("|---|---|---|---|---|---|---|---|---|")
    for p in sorted(cand, key=lambda x: int(x["id"].split("-")[0][1:])):
        r = res[p["id"]]
        print(f"| {p['id'].split('-')[0][1:]} | {p['area']} | "
              f"{', '.join(c.split()[0] for c in r['cleared'])} | "
              f"{p['certificate_cost']} | {p['evaluator_availability']} | "
              f"{p['formal_library_coverage']} | {p['reservoir_proximity']} | "
              f"{p['witness_representability']} | {p['independence_risk']} |")
    print()
    print("`CANDIDATE` means \"not ruled out by any of four mechanisms\", "
          "against a 1–3% prior for autonomous resolution. It is not a "
          "prediction that any of these 14 will be resolved, by anyone, ever.")


if __name__ == "__main__":
    main()
